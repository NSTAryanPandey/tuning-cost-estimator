"""Turn the data files into supabase/seed.sql.

Source of truth (edit these, then re-run this script):
  backend/app/data/cars.csv       one row per car model + engine
  backend/app/data/bikes.csv      one row per bike model + engine
  backend/app/data/catalogue.json stage rules, parts and labour rates

Usage:  python scripts/make_seed_sql.py
"""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "backend"))
from app.repository import load_catalogue, load_vehicles  # noqa: E402

VEHICLE_COLS = ["id", "vehicle_class", "make", "model", "engine_name", "engine_type", "year_from", "year_to",
                "stock_hp", "stock_torque_nm", "parts_multiplier", "body_type", "image_url"]


def sql_value(v):
    if v is None:
        return "null"
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, (int, float)):
        return str(v)
    if isinstance(v, list):  # engine_type[]
        return "array[" + ", ".join(sql_value(x) for x in v) + "]::engine_type[]"
    return "'" + str(v).replace("'", "''") + "'"


def insert(table, rows, cols=None):
    cols = cols or list(rows[0].keys())
    values = ",\n".join("  (" + ", ".join(sql_value(r.get(c)) for c in cols) + ")" for r in rows)
    return f"insert into {table} ({', '.join(cols)}) values\n{values};"


cat = load_catalogue()
vehicles = load_vehicles()
parts = [
    "-- Generated by scripts/make_seed_sql.py from backend/app/data. Do not edit by hand.",
    "-- " + cat["_note"],
    insert("vehicles", vehicles, VEHICLE_COLS),
    insert("stage_rules", cat["stage_rules"]),
    insert("parts", cat["parts"]),
    "select setval('parts_id_seq', (select max(id) from parts));",
    insert("labour_rates", cat["labour_rates"]),
]
out = ROOT / "supabase" / "seed.sql"
out.write_text("\n\n".join(parts) + "\n", encoding="utf-8")
print(f"Wrote {out.relative_to(ROOT)}: {len(vehicles)} vehicles")
